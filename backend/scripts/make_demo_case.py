DOCUMENTS = [
    ("01_claim.txt", "ИСКОВОЕ ЗАЯВЛЕНИЕ о взыскании задолженности", claim),
    ("02_response.txt", "ОТЗЫВ на исковое заявление", response),
    ("03_contract.txt", "ДОГОВОР ПОСТАВКИ", contract),
    ("04_receipt.txt", "ПЛАТЁЖНОЕ ПОРУЧЕНИЕ", receipt),
    ("05_protocol.txt", "ПРОТОКОЛ СУДЕБНОГО ЗАСЕДАНИЯ", protocol),
    ("06_expert_opinion.txt", "ЗАКЛЮЧЕНИЕ СУДЕБНОЙ ЭКСПЕРТИЗЫ", expert_opinion),
]

TYPES = {
    "ИСКОВОЕ ЗАЯВЛЕНИЕ о взыскании задолженности": "CLAIM",
    "ОТЗЫВ на исковое заявление": "RESPONSE",
    "ДОГОВОР ПОСТАВКИ": "CONTRACT",
    "ПЛАТЁЖНОЕ ПОРУЧЕНИЕ": "RECEIPT",
    "ПРОТОКОЛ СУДЕБНОГО ЗАСЕДАНИЯ": "PROTOCOL",
    "ЗАКЛЮЧЕНИЕ СУДЕБНОЙ ЭКСПЕРТИЗЫ": "EXPERT_OPINION",
}


def main() -> int:
    written = []
    for filename, title, builder in DOCUMENTS:
        path = DEMO / filename
        text = builder()
        path.write_text(text, encoding="utf-8")
        written.append(
            {
                "filename": filename,
                "title": title,
                "document_type": TYPES[title],
                "characters": len(text),
            }
        )

    manifest = {
        "warning": "SYNTHETIC DEMO DATA — НЕ РЕАЛЬНОЕ СУДЕБНОЕ ДЕЛО",
        "case_number": CASE_NUMBER,
        "court": COURT,
        "category": CATEGORY,
        "hearing_date": HEARING_DATE,
        "plaintiff": PLAINTIFF["name"],
        "defendant": DEFENDANT["name"],
        "claim_amount": AMOUNT,
        "documents": written,
    }
    (DEMO / "manifest.json").write_text(
        json.dumps(manifest, ensure_ascii=False, indent=2), encoding="utf-8"
    )

    print(f"создано документов: {len(written)}")
    for item in written:
        print(f"  {item['filename']:<26} {item['document_type']:<15} {item['characters']:>6} симв.")
    print()
    print("ВНИМАНИЕ: все данные вымышлены.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
