"""Предмет доказывания по категории дела (п. 5.4, 11.3 разбора).

Для каждой категории дел положен перечень обстоятельств, подлежащих
установлению. Система показывает судье таблицу: какое обстоятельство
каким документом подтверждено, а какое — ничем. Это не вывод
о правоте сторон, а карта доказательств: решение остаётся за судьёй.

Первая категория — взыскание долга по договору (поставки, купли-продажи,
возмездного оказания услуг): перечень из разбора рецензента. Обстоятельство
считается освещённым, когда хотя бы один документ дела содержит маркер
категории; этим документом и ссылается таблица. Нет ни одного —
обстоятельство остаётся непроверенным, и это должно быть видно, а не
спрятано за общими словами о «совокупности доказательств».
"""

from __future__ import annotations

from dataclasses import dataclass

from app.agents.evidence_pack import EvidenceItem


@dataclass(frozen=True)
class ProofFact:
    """Одно обстоятельство предмета доказывания и его документы."""

    circumstance: str
    docs: tuple[str, ...]
    covered: bool

    def to_dict(self) -> dict[str, object]:
        return {
            "circumstance": self.circumstance,
            "docs": list(self.docs),
            "covered": self.covered,
        }


#: Перечень обстоятельств по взысканию задолженности по договору.
#: Маркеры строчные — сверка идёт по тексту, приведённому к нижнему
#: регистру. Обстоятельства взяты из предложенного рецензентом
#: предмета доказывания (п. 5.4).
DEBT_FACTS: tuple[tuple[str, tuple[str, ...]], ...] = (
    (
        "заключение договора",
        ("договор", "соглашение", "контракт", "заключен"),
    ),
    (
        "поставка товара / оказание услуг (документы об исполнении)",
        ("накладн", "упд", "акт", "товарн", "счет-фактур", "отгрузк", "услуг"),
    ),
    (
        "факт оплаты или неоплаты",
        ("платежн", "перечислен", "оплат", "акт сверки", "задолженност", "долг"),
    ),
    (
        "размер долга",
        ("задолженност", "сумм", "цена", "стоимост", "руб"),
    ),
    (
        "расчёт неустойки или процентов",
        ("неустойк", "пен", "пени", "процент"),
    ),
)


def subject_of_proof(items: list[EvidenceItem]) -> list[ProofFact]:
    """Таблица «обстоятельство — доказательства» по материалам дела.

    Документ считается упоминанием обстоятельства, когда маркер нашёлся
    в тексте его фрагмента. По одному документу в списке источников не
    повторяемся.
    """
    facts: list[ProofFact] = []
    for circumstance, markers in DEBT_FACTS:
        docs: list[str] = []
        for item in items:
            text = item.text.lower()
            if any(marker in text for marker in markers) and (
                item.source_document not in docs
            ):
                docs.append(item.source_document)
        facts.append(
            ProofFact(
                circumstance=circumstance,
                docs=tuple(docs),
                covered=bool(docs),
            )
        )
    return facts
