"""Оценка доказательств по ст. 67 ГПК РФ (п. 5 разбора).

Рецензент: «Нет оценки доказательств: относимость, допустимость,
достоверность каждого доказательства и достаточность в совокупности.
Заключение эксперта также оценивается наравне с другими
доказательствами (ч. 3 ст. 86 ГПК РФ)». Раньше система показывала
только покрытие предмета доказывания — чем подтверждается обстоятельство,
— но не оценивало сами доказательства.

Оценку по ст. 67 ГПК РФ выносит суд, а не программа, поэтому здесь
две честные задачи:

* таблица: какие критерии оценки нашлись в тексте проекта, а какие
  нет — как предмет доказывания, только по критериям;
* вопросы наружу: позиция стороны, выданная за доказательство, и
  заключение эксперта, принятое без оценки наравне с другими
  доказательствами.

Маркеры — корни («относим», «достоверн»), а не точные фразы: падежные
формы разъезжаются, корень покрывает их все. Нахождение корня в тексте
означает «критерий упомянут», а не «доказательство оценено верно»:
первая — работа скрипта, второе — работа судьи.
"""

from __future__ import annotations

import re
from dataclasses import dataclass

#: Критерии оценки по ст. 67 ГПК РФ: три — по каждому доказательству,
#: четвёртый — по совокупности. Порядок как в статье.
CRITERIA: tuple[tuple[str, str], ...] = (
    ("относимость", "относим"),
    ("допустимость", "допустим"),
    ("достоверность", "достоверн"),
    ("достаточность в совокупности", "совокупн"),
)

#: Позиция стороны, выданная за доказательство: глагол о подтверждении
#: рядом с исковым заявлением, отзывом, возражениями или жалобой.
#: Объяснения сторон здесь не входят — они прямо отнесены к
#: доказательствам ч. 1 ст. 55 ГПК РФ, а иск и отзыв остаются
#: утверждениями стороны (ст. 55 ГПК РФ). Окно в 30 символов: шире —
#: ловит «обстоятельства установлены судом по представленным
#: доказательствам, исковое заявление принято», где заявление не
#: подтверждает ничего.
_PLEADING_RE = re.compile(
    r"(?:подтвержд|доказыва|установл|свидетельству)\w*[^\n.]{0,30}"
    r"(?:исков\w*\s+заявлен|отзыв|возражени|жалоб)"
    r"|(?:исков\w*\s+заявлен|отзыв)[^\n.]{0,30}"
    r"(?:подтвержд|доказыва|установл|свидетельству)",
    re.IGNORECASE,
)

#: «требования искового заявления подтверждаются расчётом» —
#: подтверждается расчёт, а не заявление: это верная фраза, и ловить
#: её нельзя. Исключение ищется в 40 символах перед началом совпадения.
_PLEADING_GAP_RE = re.compile(
    r"(?:требован|данными?|данных|содержан|расч[её]т|уточнен|изменен)"
    r"[^\n.]{0,30}исков\w*\s+заявлен",
    re.IGNORECASE,
)

#: Экспертиза в материалах дела и в проекте — один корень, разные
#: источники проверки.
_EXPERT_RE = re.compile(r"эксперт|экспертиз", re.IGNORECASE)

#: Ссылка на доказательства как на класс: «проект ссылается на
#: доказательства, но их не оценивает».
_EVIDENCE_RE = re.compile(r"доказательств|доказательству", re.IGNORECASE)


@dataclass(frozen=True)
class AssessmentCriterion:
    """Один критерий оценки и то, найден ли он в проекте."""

    criterion: str
    marker: str
    covered: bool

    def to_dict(self) -> dict[str, object]:
        return {
            "criterion": self.criterion,
            "marker": self.marker,
            "covered": self.covered,
        }


@dataclass(frozen=True)
class AssessmentFinding:
    """Вопрос об оценке доказательств, который судья должен разрешить."""

    kind: str  # "pleading_as_evidence" | "expert_unassessed" | "not_assessed"
    reason: str
    evidence: str = ""  # фрагмент проекта, вызвавший вопрос


def assessment_of(draft_text: str) -> list[AssessmentCriterion]:
    """Какие критерии ст. 67 ГПК РФ нашлись в тексте проекта."""
    lower = draft_text.lower()
    return [
        AssessmentCriterion(
            criterion=name, marker=marker, covered=marker in lower
        )
        for name, marker in CRITERIA
    ]


def _pleading_matches(text: str) -> list[re.Match[str]]:
    """Совпадения «позиция стороны как доказательство» без ложных.

    Из найденных отбрасываются те, перед которыми стоит слово-исключение:
    подтверждается расчёт или уточнение, а не само заявление.
    """
    kept: list[re.Match[str]] = []
    for match in _PLEADING_RE.finditer(text):
        window_start = max(0, match.start() - 40)
        if _PLEADING_GAP_RE.search(text[window_start : match.end()]):
            continue
        kept.append(match)
    return kept


def check_evidence_assessment(
    draft_text: str, material_texts: list[str]
) -> list[AssessmentFinding]:
    """Вопросы об оценке доказательств (ст. 67, ч. 3 ст. 86 ГПК РФ).

    Материалы дела нужны для заключения эксперта: вопрос задаётся
    только когда экспертиза есть в деле и проект на неё ссылается.
    Нет упоминания — нет и вопроса: отсутствие слова не повод
    что-то требовать.
    """
    lower = draft_text.lower()
    findings: list[AssessmentFinding] = []

    # Позиция стороны как доказательство — независимо от того, есть ли
    # остальная оценка: это ошибка вида, а не пробел.
    for match in _pleading_matches(lower):
        findings.append(
            AssessmentFinding(
                kind="pleading_as_evidence",
                evidence=lower[match.start() : match.end()][:100],
                reason=(
                    "проект опирается на позицию стороны как на "
                    "доказательство: исковое заявление и отзыв — это "
                    "утверждения стороны, а не сведения о фактах; "
                    "обстоятельство надлежит подтвердить доказательством "
                    "(ст. 55 ГПК РФ)"
                ),
            )
        )
        break  # Один вопрос, а не пачка на каждый глагол.

    covered_any = any(marker in lower for _name, marker in CRITERIA)

    expert_in_case = any(_EXPERT_RE.search(text) for text in material_texts)
    if expert_in_case and _EXPERT_RE.search(lower):
        # Оценён ли эксперт по существу: критерий ст. 67 в том же
        # предложении, что и упоминание экспертизы. Упоминание критерия
        # в другом месте проекта не отменяет вопрос (дефект D6), но и
        # явная оценка эксперта вопроса не вызывает.
        assessed = any(
            _EXPERT_RE.search(sentence)
            and any(marker in sentence for _name, marker in CRITERIA)
            for sentence in re.split(r"[.\n]", lower)
        )
        if not assessed:
            findings.append(
                AssessmentFinding(
                    kind="expert_unassessed",
                    reason=(
                        "в деле заключение эксперта, проект ссылается на "
                        "него, но не содержит оценки по критериям ст. 67 ГПК "
                        "РФ: заключение исследуется наравне с другими "
                        "доказательствами, оценивает его суд (ч. 3 ст. 86 ГПК "
                        "РФ)"
                    ),
                )
            )
    elif not covered_any and _EVIDENCE_RE.search(lower):
        findings.append(
            AssessmentFinding(
                kind="not_assessed",
                reason=(
                    "проект ссылается на доказательства, но не оценивает "
                    "их по ст. 67 ГПК РФ (относимость, допустимость, "
                    "достоверность); оценка принадлежит суду — включить "
                    "ли её в проект, решает судья"
                ),
            )
        )

    return findings
