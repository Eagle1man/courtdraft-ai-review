def _reference(claim: MoneyClaim) -> str:
    """Основание и источник требования одной строкой.

    Отдельная функция, потому что при незаполненном источнике в скобках
    остаётся висячая запятая: «(расходы на представителя, )». Это
    выглядит как недоделка и в проекте решения выглядит неопрятно.
    """
    parts = [claim.basis]
    if claim.source:
        parts.append(claim.source)
    return f"({', '.join(parts)})"


def _satisfy(
    claim: MoneyClaim, outcome: Outcome, parties: Parties
) -> tuple[str, list[str]]:
    """Пункт решения по денежному требованию."""
    gaps: list[str] = []

    if not isinstance(outcome, Outcome):
        raise TypeError(f"outcome должен быть Outcome, получено {type(outcome)}")
    if outcome is Outcome.DENIED:
        return (
            f"Отказать в удовлетворении исковых требований истца "
            f"{_reference(claim)}.",
            gaps,
        )

    if claim.amount is None:
        gaps.append(f"не указана сумма по требованию «{claim.basis}»")
        amount_text = REVIEW
    else:
        amount_text = _amount(claim.amount, claim.kopecks)

    if not claim.source:
        gaps.append(f"не указан источник суммы по требованию «{claim.basis}»")

    payer = parties.defendant_genitive
    payee = parties.plaintiff_genitive

    if outcome is Outcome.SATISFIED:
        # «В полном объёме» — самая частая формулировка в решениях:
        # 289 документов из 1425 (20,3 %). Без неё судья не видит
        # границы взыскания и должен догадываться, решено ли
        # требование целиком или часть оставлена без рассмотрения.
        return (
            f"Удовлетворить исковые требования истца в полном объёме: "
            f"взыскать с {payer} в пользу {payee} {amount_text} "
            f"{_reference(claim)}.",
            gaps,
        )

    # Частичное удовлетворение. Сумма удовлетворённой части обязана
    # быть названа явно: иначе исполнительный лист предъявить нечем.
    if claim.granted_amount is None:
        gaps.append(
            f"по частичному удовлетворению не указана сумма, "
            f"удовлетворённая судом (требование «{claim.basis}»)"
        )
        granted_text = REVIEW
    else:
        granted_text = _amount(claim.granted_amount, claim.granted_kopecks)

    detail = f"; {claim.grounds}" if claim.grounds else ""
    reference = f"({claim.basis}{detail})"
    return (
        f"Удовлетворить исковые требования истца частично: взыскать с "
        f"{payer} в пользу {payee} {granted_text} "
        f"{reference}. В остальной части отказать в "
        f"удовлетворении исковых требований истца.",
        gaps,
    )


def _render_counter_claim(
    counter: CounterClaim, named: Parties
) -> str:
    """Собрать пункт по встречному требованию ответчика.

    Направление платежа обратное: отвечает истец, в пользу ответчика.
    Ошибка здесь не косметическая — «взыскать с ответчика» вместо «с
    истца» предписывает платёж не тому, и такой проект решения влечёт
    реальные убытки стороне.

    Формулировки взяты из решений: «В удовлетворении встречных
    исковых требований … отказать» и «Принять встречное исковое
    заявление …».

    Если сумма не установлена, подставляется не ноль, а видимая
    пометка: судья должен увидеть, что цифры нет, а не получить
    предписание взыскать ноль.
    """
    subject = "встречных исковых требований ответчика"
    if counter.outcome is Outcome.DENIED:
        return (
            f"В удовлетворении {subject} ({counter.basis}, "
            f"{counter.source}) отказать."
        )
    if counter.amount is None:
        return (
            f"Удовлетворить {subject} ({counter.basis}, "
            f"{counter.source}): взыскать с {named.plaintiff_genitive} в "
            f"пользу {named.defendant_genitive} {REVIEW} (сумма не "
            f"установлена)."
        )
    return (
        f"Удовлетворить {subject} ({counter.basis}, {counter.source}): "
        f"взыскать с {named.plaintiff_genitive} в пользу "
        f"{named.defendant_genitive} {_amount(counter.amount, counter.kopecks)}."
    )


def build_operative(
    money_claims: list[MoneyClaim],
    other_claims: list[Claimant] | None = None,
    *,
    counter_claims: list[CounterClaim] | None = None,
    fee_paid: float | None = None,
    costs: float | None = None,
    fee_stakes: bool = True,
    fee_exempt: bool = False,
    parties: Parties | None = None,
    total_line: bool = True,
    legal_basis: str = DEFAULT_LEGAL_BASIS,
    procedure: Procedure = Procedure.ORDINARY,
    budget: str = "",
) -> OperativePart:
    """Собрать резолютивную часть решения.

    Порядок пунктов соответствует ГПК РФ: сначала разрешение по
    требованиям по существу, затем разрешение по иным требованиям
    (признание, исполнение обязательства), затем распределение
    расходов, затем объявление права на обжалование.

    Аргументы:
        money_claims: денежные требования, извлечённые из материалов.
        other_claims: требования без денежной суммы.
        counter_claims: встречные требования ответчика. Направление
            платежа у них обратное, поэтому они разрешаются отдельно
            и не смешиваются с требованиями истца.
        fee_paid: размер госпошлины, уплаченной истцом. None означает,
            что сумма не установлена, — тогда пункт не выносится, а
            в пропуски попадает требование проверить.
        costs: сумма, подлежащая взысканию в качестве расходов.
        fee_stakes: указывать ли требование о распределении расходов.
        fee_exempt: был ли истец освобождён от уплаты пошлины. По
            умолчанию нет, и тогда пошлина взыскивается в пользу истца
            (ч. 1 ст. 98 ГПК РФ). Только при освобождении пошлина идёт
            в доход бюджета (ч. 1 ст. 103 ГПК РФ).
        parties: названия сторон. Пустые поля подставляют родовые
            слова «истец» и «ответчик».
        total_line: выводить ли итог «а всего …». По разбору решений
            итог присутствует в 189 случаях из 1 425 и суммирует
            взыскание с пошлинами, поэтому за него берётся сумма
            всех требований плюс пошлина.
        legal_basis: норма, которой суд обосновывает решение. По
            умолчанию ст. 198 ГПК РФ; для особых производств
            (заочное, приказное) задаётся своя.
        procedure: порядок рассмотрения дела. Заочное производство —
            49 % гражданских дел по разбору решений, и без него
            резолюция получалась бы неполной.
        budget: бюджет, в доход которого взыскивается госпошлина,
            когда истец освобождён от её уплаты (см. fee_exempt).
            Если бюджет неизвестен, остаётся видимая пометка.

    Возвращает:
        OperativePart с пунктами и списком пропусков.
    """
    # Заочное производство меняет и основание решения, и право на
    # обжалование, поэтому подставляется автоматически — иначе судья
    # получил бы «ст. 198 ГПК РФ» без ст. 233, то есть неполную ссылку.
    if procedure is Procedure.DEFAULT:
        legal_basis = legal_basis.replace(
            DEFAULT_LEGAL_BASIS, DEFAULT_ARTICLE, 1
        )

    result = OperativePart(legal_basis=legal_basis)
    named = parties or Parties()

    # Вводная формула резолютивной части. Раньше legal_basis вычислялся
    # и хранился, но в текст не выводился: резолюция начиналась сразу с
    # «Удовлетворить…», без «Руководствуясь ст. 198 ГПК РФ, суд решил».
    # Без этой строки резолютивная часть не читается как часть решения.
    # При пустых требованиях формулу не ставим: резолюция обязана
    # остаться пометкой о проверке, а не выглядеть пустым решением.
    if money_claims:
        result.items.append(f"Руководствуясь {legal_basis}, суд решил:")

    # Падеж названий сторон известен не всегда: человек с нестандартным
    # окончанием остаётся в именительном, и это должно быть видно судье,
    # а не тонуть в тексте акта.
    for uncertain in named.uncertain_cases:
        result.gaps.append(
            f"название стороны «{uncertain}» не приведено к родительному "
            f"падежу — проверить склонение в резолютивной части"
        )

    # 0. Порядок рассмотрения. В решениях этот пункт идёт первым в
    #    резолютивной части: законно решить дело в отсутствие стороны
    #    можно не всегда, и суд обязан это обосновать.
    if procedure in _PROCEDURE_ITEMS:
        result.items.append(_PROCEDURE_ITEMS[procedure])

    # Пропуск об отсутствии требований ставится только если нечего
    # разрешать вовсе. Встречное требование ответчика тоже предмет
    # разрешения: если по иску не нашлось ничего, а ответчик заявил
    # встречный иск, решение всё равно не пустое.
    if not money_claims and not other_claims and not counter_claims:
        result.gaps.append("в материалах дела не найдено ни одного требования")
        return result

    # 1. Требования по существу.
    granted: list[tuple[float, int]] = []
    for claim in money_claims:
        text, gaps = _satisfy(claim, claim.outcome, named)
        result.items.append(text)
        result.gaps.extend(gaps)
        # В итог входит только то, что реально взыскивается: отказ и
        # частичное удовлетворение не дают полной суммы.
        if claim.outcome is Outcome.SATISFIED and claim.amount is not None:
            granted.append((claim.amount, claim.kopecks))
        elif (
            claim.outcome is Outcome.PARTIAL
            and claim.granted_amount is not None
        ):
            # Копейки присуждённой суммы, а не копейки требования:
            # при иске 7 000,50 и присуждении 2 000,25 итог иначе
            # набирал бы 2 000,50 — пятьдесят копеек из чужого числа.
            granted.append((claim.granted_amount, claim.granted_kopecks))

    # 2. Иные требования. Переменная названа иначе, чем в первом цикле:
    #    иначе вывод типа в mypy цепляется за MoneyClaim из первого
    #    цикла и ругается на отсутствие поля description.
    extra: Sequence[Claimant] = tuple(other_claims or ())
    for other in extra:
        if not other.description:
            result.gaps.append("требование без описания")
            continue
        if not other.source:
            result.gaps.append(
                f"не указан источник требования «{other.description}»"
            )
        if other.outcome is Outcome.DENIED:
            result.items.append(
                f"Отказать в удовлетворении требования истца "
                f"({other.description})."
            )
        else:
            result.items.append(
                f"Удовлетворить требование истца: {other.description} "
                f"({other.source})."
            )

    # 3. Встречные требования ответчика. Идут после основных, потому
    #    что в решениях их разрешают после разрешения иска: ответчик
    #    заявил требование в ходе рассмотрения. Направление платежа
    #    обратное — платит истец в пользу ответчика.
    for counter in counter_claims or ():
        result.items.append(_render_counter_claim(counter, named))
        # В итог входит только реально взыскиваемое по встречному
        # требованию: отказ в нём ничего не добавляет.
        if counter.outcome is Outcome.SATISFIED and counter.amount is not None:
            granted.append((counter.amount, counter.kopecks))

    # 4. Распределение расходов. Пункт обязателен по ст. 98 ГПК РФ,
    #    поэтому отсутствие суммы не повод пропустить его целиком —
    #    повод оставить незаполненным и сказать об этом.
    #
    #    Частичное удовлетворение меняет саму форму пункта: ч. 1 ст. 98
    #    ГПК РФ присуждает расходы ПРОПОРЦИОНАЛЬНО размеру
    #    удовлетворённых требований. Раньше проект взыскивал пошлину
    #    полной суммой (как при полном удовлетворении), и при отказе
    #    в части иска пункт противоречил закону. Пропорцию не считает
    #    ни система (число без материалов — выдумка) ни черновик: её
    #    считает судья, поэтому сумма остаётся пометкой с пробелом.
    proportional = any(
        claim.outcome is not Outcome.SATISFIED for claim in money_claims
    )
    if fee_stakes:
        if fee_paid is None:
            result.gaps.append(
                "не установлен размер государственной пошлины — "
                "пункт о распределении расходов требует проверки"
            )
        else:
            # Направление пошлины. По умолчанию она идёт В ПОЛЬЗУ
            # ИСТЦА (ч. 1 ст. 98 ГПК РФ): пошлину уплачивает истец, и
            # при удовлетворении иска суд присуждает ему понесённые
            # расходы. В доход бюджета пошлина взыскивается только
            # тогда, когда истец был освобождён от её уплаты
            # (ч. 1 ст. 103 ГПК РФ).
            #
            # Раньше здесь стояло наоборот, и обоснованием была частота:
            # «в доход бюджета» встречается в 98 решениях из 1 425.
            # Частота в судебной практике — не довод: суды встречаются и
            # с тем, и с другим, а правило задаёт закон. Ошибка была
            # дорогой: пункт отправлял пошлину в бюджет, а итог «а всего»
            # включал её в сумму, взыскиваемую в пользу истца, то есть
            # проект противоречил сам себе двумя строками ниже.
            if fee_exempt:
                if budget:
                    item = (
                        f"Взыскать с {named.defendant_genitive} в доход "
                        f"бюджета {budget} государственную пошлину "
                        f"в размере {_amount(fee_paid)} (ст. 103 ГПК РФ)."
                    )
                else:
                    item = (
                        f"Взыскать с {named.defendant_genitive} "
                        f"{REVIEW} (доход бюджета) государственную пошлину "
                        f"в размере {_amount(fee_paid)} (ст. 103 ГПК РФ)."
                    )
                    result.gaps.append(
                        "не установлен бюджет, в доход которого взыскивается "
                        "государственная пошлина"
                    )
            else:
                if proportional:
                    item = (
                        f"Взыскать с {named.defendant_genitive} в пользу "
                        f"{named.plaintiff_genitive} государственную пошлину "
                        f"пропорционально размеру удовлетворённых исковых "
                        f"требований в размере {REVIEW} "
                        f"(ч. 1 ст. 98 ГПК РФ)."
                    )
                    result.gaps.append(
                        "исход по части требований не полный — размер "
                        "госпошлины пропорционален удовлетворённой части "
                        "и требует расчёта судьи"
                    )
                else:
                    item = (
                        f"Взыскать с {named.defendant_genitive} в пользу "
                        f"{named.plaintiff_genitive} государственную пошлину "
                        f"в размере {_amount(fee_paid)} (ст. 98 ГПК РФ)."
                    )
            if costs is not None:
                # Иные расходы (в отличие от пошлины) возвращаются
                # истцу: он их понёс. При частичном удовлетворении они
                # тоже делятся пропорционально (ч. 1 ст. 98 ГПК РФ
                # относит к расходам и иные издержки, понесённые
                # стороной).
                if proportional:
                    item += (
                        f" Взыскать с {named.defendant_genitive} в пользу "
                        f"{named.plaintiff_genitive} иные расходы "
                        f"пропорционально размеру удовлетворённых исковых "
                        f"требований в размере {REVIEW} (ст. 100 ГПК РФ)."
                    )
                else:
                    item += (
                        f" Взыскать с {named.defendant_genitive} в пользу "
                        f"{named.plaintiff_genitive} иные расходы в размере "
                        f"{_amount(costs)} (ст. 100 ГПК РФ)."
                    )
            result.items.append(item)
            # При пропорциональном распределении сумма расходов неизвестна
            # и в итог «а всего» не входит: туда попадает только то, что
            # взыскивается в определённом размере.
            if not proportional:
                granted.append((fee_paid, 0))
                if costs is not None:
                    granted.append((costs, 0))

    # Иные расходы по ст. 100 ГПК РФ не зависят от пошлины: их понёс
    # истец, и суд возвращает их независимо от того, известна ли
    # пошлина. Раньше пункт о них жил внутри блока пошлины, и в деле
    # без пошлины (real-04) иные расходы исчезали из проекта целиком
    # и не попадали в итог «а всего».
    #
    # Флаг fee_stakes означает «не выводить требование о распределении
    # расходов» — это касается и ст. 100, поэтому иные расходы под
    # флагом тоже не выводятся.
    if costs is not None and fee_stakes and not (fee_paid is not None):
        if proportional:
            result.items.append(
                f"Взыскать с {named.defendant_genitive} в пользу "
                f"{named.plaintiff_genitive} иные расходы пропорционально "
                f"размеру удовлетворённых исковых требований в размере "
                f"{REVIEW} (ст. 100 ГПК РФ)."
            )
            result.gaps.append(
                "исход по части требований не полный — размер иных "
                "расходов пропорционален удовлетворённой части и "
                "требует расчёта судьи"
            )
        else:
            result.items.append(
                f"Взыскать с {named.defendant_genitive} в пользу "
                f"{named.plaintiff_genitive} иные расходы в размере "
                f"{_amount(costs)} (ст. 100 ГПК РФ)."
            )
            granted.append((costs, 0))

    # 5. Итог «а всего». Так пишут в резолюции: одна цифра, из которой
    #    видно общий размер взыскания.
    if total_line and granted:
        total_rubles, total_kopecks = _sum_amounts(granted)
        result.items.append(
            f"Всего подлежит взысканию "
            f"{_amount_with_words(total_rubles, total_kopecks)}"
        )

    # 6. Последствия заочного решения идут ДО права на обжалование.
    #    Заочное решение можно отменить заявлением ответчика, и без
    #    этого пункта он лишён права: в разборе 1 425 резолюций об
    #    отмене пишут 640 решений, о семидневном сроке — 378.
    if procedure is Procedure.DEFAULT:
        result.items.append(DEFAULT_CONSEQUENCE)
        result.items.append(
            "Заочное решение может быть обжаловано в апелляционном порядке "
            "в течение месяца по истечении срока подачи ответчиком заявления "
            "об отмене этого решения суда, а в случае, если такое заявление "
            "подано, — в течение месяца со дня вынесения определения суда "
            "об отказе в удовлетворении этого заявления "
            "(ст. 332 ГПК РФ)."
        )
    else:
        # 6. Право на обжалование. Не заполняется моделью никогда.
        result.items.append(
            "Решение может быть обжаловано в апелляционном порядке в течение "
            "месяца со дня принятия решения в окончательной форме, если иные "
            "сроки не установлены настоящим Кодексом (ст. 321 ГПК РФ)."
        )

    return result


# Проверки, что конструкции не разъезжаются между собой.
_SATISFY = re.compile(r"взыскать с ответчика в пользу истца", re.I)
_DENY = re.compile(r"Отказать в удовлетворении исковых требований", re.I)


def selfcheck() -> list[str]:
    """Прогнать типовые случаи и вернуть список расхождений."""
    problems: list[str] = []

    full = MoneyClaim(amount=150000, basis="неуплаченная по договору поставки",
                      source="договор поставки № 14, чек")
    part = MoneyClaim(amount=150000, granted_amount=90000,
                      basis="неустойка по договору", source="договор № 14",
                      grounds="суд не нашёл нарушения в части",
                      outcome=Outcome.PARTIAL)
    denied = MoneyClaim(amount=150000, basis="убытки",
                        source="экспертиза № 5", outcome=Outcome.DENIED)

    full_text = build_operative([full], fee_paid=5100).render()
    if not _SATISFY.search(full_text):
        problems.append("полное удовлетворение: нет конструкции «взыскать с»")
    if "150 000" not in full_text:
        problems.append("полное удовлетворение: сумма не отформатирована")
    if "ст. 98" not in full_text:
        problems.append("пошлины: нет ссылки на ст. 98 ГПК РФ")

    part_text = build_operative([part], fee_paid=5100).render()
    if "90 000" not in part_text:
        problems.append("частичное удовлетворение: нет суммы удовлетворённой части")
    if "В остальной части отказать" not in part_text:
        problems.append("частичное удовлетворение: нет отказа в остальной части")

    deny_text = build_operative([denied], fee_paid=5100).render()
    if not _DENY.search(deny_text):
        problems.append("отказ: нет формулы отказа")
    # Проверяется именно пункт по требованию, а не весь текст: пункт
    # о государственной пошлине при отказе по существу остаётся.
    if "взыскать с ответчика в пользу истца 150 000" in deny_text.lower():
        problems.append("отказ: по требованию взыскание вынесено")

    # Сумма не извлечена: пункт остаётся незаполненным.
    unknown = MoneyClaim(amount=None, basis="расходы на представителя",
                         source="")
    gap_text = build_operative([unknown], fee_paid=None).render()
    if REVIEW not in gap_text:
        problems.append("неизвестная сумма: нет пометки о проверке")
    if gap_text.count(REVIEW) < 2:
        problems.append("неизвестная сумма: пропусков должно быть два")

    empty = build_operative([]).render()
    if REVIEW not in empty:
        problems.append("пустые требования: нет пометки о проверке")

    # Итог и копейки — по разбору настоящих решений.
    with_kop = MoneyClaim(amount=5034, kopecks=79, basis="задолженность",
                          source="начисление")
    kop_text = build_operative([with_kop], fee_paid=400).render()
    if "5 034 руб. 79 коп." not in kop_text:
        problems.append("копейки: сумма не отформатирована с копейками")
    if "а всего" not in kop_text and "Всего подлежит взысканию" not in kop_text:
        problems.append("итог: строка «всего» не построена")

    return problems
