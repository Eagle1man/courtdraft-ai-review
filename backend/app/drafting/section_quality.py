"""Пригодность ответа модели как текста раздела решения.

На маленьких моделях вместо текста акта часто приходит пересказ хода
работы: «Okay, let's tackle this… The materials don't specify…». Такой
текст — не раздел решения, а болтовня модели.

На живом прогоне описательная часть пришла в таком виде: 1601 латинская
буква против 70 кириллических. В проект решения и в демонстрацию
заказчику попало именно это.

Молча выбросить такой ответ нельзя: судья увидит в проекте чужую
болтовню и решит, что система не работает. Честная отметка «раздел не
сформирован» с причиной полезнее мусора и соответствует правилу
продукта: неизвестное показывается как неизвестное.
"""

from __future__ import annotations

import re

#: Слова, по которым узнаётся рассуждение модели.
REASONING_MARKERS = (
    "wait,",
    "wait ",
    "okay, let",
    "let's tackle",
    "i need to",
    "the user wants",
    "the materials don't",
    "the court needs to",
    "first, i need",
    "let me think",
    "i should look",
    "the key points are",
)

#: Доля кириллицы среди букв, ниже которой текст не считается
#: русским. Порог низкий намеренно: в судебном тексте всегда есть
#: латиница — номера статей, «ООО», «руб.» — но рассуждение на
#: английском не становится русским текстом оттого, что в нём есть
#: слово «суд».
CYRILLIC_RATIO_FLOOR = 0.35


def unusable_reason(text: str) -> str:
    """Почему ответ модели нельзя показать как раздел решения.

    Пустая строка означает, что текст пригоден.
    """
    cleaned = text.strip()
    if not cleaned:
        return "модель вернула пустой ответ"

    letters = [ch for ch in cleaned if ch.isalpha()]
    if not letters:
        return "в ответе нет ни одной буквы"

    cyrillic = sum(
        1 for ch in letters if "а" <= ch.lower() <= "я" or ch in "ёЁ"
    )
    ratio = cyrillic / len(letters)
    if ratio < CYRILLIC_RATIO_FLOOR:
        return (
            "модель вернула текст не на русском языке "
            f"(кириллицы {ratio:.0%} от букв) — похоже на рассуждения"
        )

    lowered = cleaned.lower()
    for marker in REASONING_MARKERS:
        if marker in lowered:
            return (
                "модель описала ход своих рассуждений вместо текста раздела"
            )

    # Ключ сравнения нормализуется: без этого повтор, отличающийся
    # одним знаком препинания, считался новой фразой, и зацикливание
    # проходило мимо проверки. Сравнивать надо фразу, а не пунктуацию.
    keys = [
        re.sub(r"\W+", "", part.lower())[:60]
        for part in re.split(r"[.!?]\s+", cleaned)
        if len(part.strip()) > 30
    ]
    if keys and len(set(keys)) * 2 < len(keys):
        return "модель повторила одну и ту же фразу несколько раз"

    return ""


NOT_FORMED = "Раздел не сформирован: {reason}. {review}"


def not_formed_text(reason: str, review: str) -> str:
    """Текст-заглушка для непригодного ответа модели.

    Подставляется вместо текста раздела и всегда содержит пометку
    проверки: судья должен видеть, что раздел пуст не из-за ошибки
    интерфейса, а потому что модель не дала пригодного текста.
    """
    return NOT_FORMED.format(reason=reason, review=review)
