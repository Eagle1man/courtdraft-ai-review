"""Признаки требования истца — общее место для двух модулей.

Зачем отдельный модуль. Требование истца опознаётся в двух местах:
  - при сборке пакета доказательств, чтобы положить фразу в категорию
    «claims» (app.agents.evidence_pack);
  - при извлечении требований для резолютивной части
    (app.drafting.requirements).

Если формулировки будут написаны дважды, они разойдутся: категория
«claims» попадёт в пакет, а извлечение её не увидит, и резолютивная
часть окажется пустой при полном пакете. Именно это и происходило до
появления модуля: в пакете из 46 фактов в «claims» попадал один, и тот
не был требованием.

ПОЧЕМУ ФОРМЫ ОГРАНИЧЕНЫ, А НЕ ЧЕРЕЗ \\w+
    Широкая подстановка давала ложные срабатывания на живых текстах:
    «просрочка» попадала под «просить», а «обязательства» — под
    «обязать». Обе формы — существительные, а не требование, и такие
    фразы в раздел «суд решил» попадать не должны.
"""

from __future__ import annotations

import re

# Глаголы требования в тех формах, в которых они пишутся в заявлениях.
# «удовлетворить» намеренно отсутствует: им описывают обоснование
# («считает возможным удовлетворить»), а не требование истца.
CLAIM_VERB = (
    r"(?:\bтребу(?:ет|ют|ем|ешь|йте)\b|\bтребовать\b|"
    r"\bпрос(?:ит|ят|им|ишь|ите)\b|\bпрошу\b|"
    r"\bвзыска(?:ть|ть\b)|\bвзыскивани\w+|\bвзыска\b|"
    r"\bвозмести(?:ть|м|ть)\b|"
    r"\bобяза(?:ть|ть|ться|л[ао])\b|"
    r"\bпризна(?:ть|ем|ет)\b|\bпризна[ао]\b|"
    r"\bпривлечь\b|\bвосстанови(?:ть|л|ла)\b|\bотмени(?:ть|л)\b)"
    # Начало с существительного, а не с глагола. Такое пишут и в
    # заявлениях, и в самих решениях:
    #     Требования о компенсации морального вреда подлежат
    #     удовлетворению.
    #     Иск о взыскании убытков, процентов… — удовлетворить.
    # Без этого требование оставалось незамеченным, хотя основание
    # и сумма в нём были.
    #
    # Предлог «о» после «требования» обязателен: без него проходила
    # фраза «поддерживает исковые требования», где требования лишь
    # упомянуты, а не заявлены.
    r"|\bтребования\b\s*(?:о|об)\s+"
    r"|\bиск\s+о\b\s+взыскани"
)

CLAIM_VERB_RE = re.compile(CLAIM_VERB, re.I)

# «Взыскать С ИСТЦА» — это не требование истца, а возражение ответчика
# или предложение суда. Если такая фраза попадёт в требования, система
# построит пункт «взыскать с истца», то есть перевернёт стороны. Это ровно
# тот дефект, который проверка проекта уже ловила как CRITICAL, и
# допускать его на входе нельзя: резолютивная часть собирается по
# правилам и обязана считать, что платит ответчик.
PAYER_IS_PLAINTIFF_RE = re.compile(
    r"(?:взыск\w+|удержан\w+|списа\w+)\s+(?:с\s+)?истц\w*"
    r"|(?:с\s+)?истц\w*\s+(?:в пользу\s+)?ответчик\w*",
    re.I,
)

# Условие договора («Поставщик обязуется передать товар») — это
# доказательство, а не требование истца. Такие фразы приходят из
# текста договора и в раздел «суд решил» попадать не должны.
CONTRACT_CLAUSE_RE = re.compile(
    r"\bпоставщик\b.*\bобязуется\b|\bпокупатель\w*\s+обязуется\b",
    re.I,
)


def looks_like_claim(text: str) -> bool:
    """Похоже ли это на требование истца, а не на обоснование.

    Проверяется и направление платежа, и характер фразы: «взыскать с
    истца» и условие договора требованиями истца не являются.
    """
    if not CLAIM_VERB_RE.search(text):
        return False
    if PAYER_IS_PLAINTIFF_RE.search(text):
        return False
    return not CONTRACT_CLAUSE_RE.search(text)


def payer_is_plaintiff(text: str) -> bool:
    """Платёж направлен с истца — требованием это быть не может."""
    return bool(PAYER_IS_PLAINTIFF_RE.search(text))


# Промежуток между «взыскать» и основанием. В заявлении там стоят
# стороны и их роли: «взыскать с Фирма «...» в пользу Образцов
# Пётр Петрович задолженность». Жёсткое «взыскать (с X)? (в пользу Y)?
# основание» на живом тексте не срабатывало, и основание не
# определялось.
#
# Стоп-символы здесь принципиальны. Без них промежуток перешагивал
# границу следующего требования и первая сумма доставалась обеим:
# на демо «неустойка» получала 150 000 руб. вместо своих 90 000.
# Поэтому переход через точку с запятой, двоеточие и номера пунктов
# запрещён — там начинается новое требование.
_BETWEEN = r"(?:(?!\d+\.\s|[;:]|\bv размере\b|\bв сумме\b)[^.;:]){0,160}?"

# Основание требования. Порядок значим: первый подошедший и даёт
# основание, поэтому более общие формулы стоят после более конкретных.
# Иначе требование о неустойке сводилось бы к общему «взыскать долг».
CLAIM_BASIS_PATTERNS: list[tuple[re.Pattern[str], str]] = [
    (
        # Между «на» и «представителя» в живых материалах стоят
        # слова: «расходы на оплату услуг представителя», «расходы на
        # юридическую помощь представителя». Прежний вид требовал
        # «на» вплотную к «представител», и на живом тексте основание
        # не определялось вовсе — требование уходило в непознанные и
        # в резолюцию не попадало.
        re.compile(
            r"(?:взыска\w+|возмести\w*)\s+" + _BETWEEN
            + r"(?:возмещен\w*\s+)?расход\w*\s+на\s+(?:[\w-]+\s+){0,4}"
            r"(?:представител\w+|юрист\w+|адвокат\w+|юридическ\w*\s+услуг)",
            re.I,
        ),
        "расходы на представителя",
    ),
    (
        # Проценты за пользование чужими денежными средствами — ст. 395
        # ГК РФ. Это самостоятельное основание, а не неустойка: суды
        # называют его отдельно в 63 резолюциях (4,4 %), и смешивать
        # его с неустойкой нельзя — у них разные основания и разный
        # порядок расчёта.
        re.compile(
            r"(?:взыска\w+|возмести\w*)\s+" + _BETWEEN
            + r"процент\w*\s+за\s+пользовани\w+",
            re.I,
        ),
        "проценты за пользование денежными средствами",
    ),
    (
        # Компенсация морального вреда — ст. 151 ГК РФ. Встречается
        # в 131 резолюции (9,2 %), то есть в каждой десятой.
        re.compile(
            r"(?:взыска\w+|возмести\w*|компенсац\w*)\s+" + _BETWEEN
            + r"(?:компенсаци\w+\s+)?моральн\w*\s+вред",
            re.I,
        ),
        "компенсация морального вреда",
    ),
    (
        re.compile(
            r"(?:взыска\w+|возмести\w*)\s+" + _BETWEEN
            + r"(неустойк\w*|пен[яи]|проценты|штраф\w*|"
            r"неосновательн\w+\s+обогащен\w*)",
            re.I,
        ),
        "неустойка и санкции",
    ),
    (
        re.compile(
            r"(?:взыска\w+|возмести\w*)\s+" + _BETWEEN
            + r"(компенсац\w*|моральн\w*\s+вред)",
            re.I,
        ),
        "компенсация",
    ),
    (
        re.compile(
            r"(?:взыска\w+|возмести\w*)\s+" + _BETWEEN
            + r"(убытк\w*|реальный\s+ущерб|ущерб)",
            re.I,
        ),
        "убытки",
    ),
    (
        re.compile(
            r"(?:взыска\w+|возмести\w*)\s+" + _BETWEEN
            + r"(задолженност\w*|долг|стоимость\s+товара)",
            re.I,
        ),
        "задолженность по договору",
    ),
    (
        re.compile(
            r"признать\s+" + _BETWEEN
            + r"(недействительн\w+|незаключённ\w+|ничтожн\w+)",
            re.I,
        ),
        "признание договора недействительным",
    ),
    (
        re.compile(r"признать\s+право\s+(?:собственности|требования)", re.I),
        "признание права",
    ),
    (
        re.compile(
            r"обязать\s+" + _BETWEEN + r"(?:перечислить|оплатить|уплатить)", re.I
        ),
        "обязать совершить действие",
    ),
    (
        # Расторжение договора — самое частое неимущественное требование
        # в договорных спорах. Без него требование уходило в список
        # неопознанных и до резолютивной части не доходило вовсе: в деле
        # real-04 расторжение было заявлено, а в проекте решения
        # отсутствовало.
        re.compile(
            r"(?:расторгнуть|расторжени\w+)\s+" + _BETWEEN
            + r"(?:договор\w*|контракт\w*|соглашени\w+)",
            re.I,
        ),
        "расторжение договора",
    ),
    (
        re.compile(
            r"(?:отказаться|отказ\w*)\s+от\s+исполнени\w+\s+" + _BETWEEN
            + r"(?:договор\w*|обязательств\w+|соглашени\w+)",
            re.I,
        ),
        "отказ от исполнения договора",
    ),
]

# Якоря оснований: слова, по которым основание опознаётся внутри
# отдельного пункта перечисления. Нужны для по��пунктного извлечения
# («ущерб 10 490, неустойка 2 202, моральный вред 10 000»): в одном
# окне требований несколько, и каждое требует своей суммы.
#
# Порядок значим, как и в CLAIM_BASIS_PATTERNS: более конкретное
# основание стоит раньше, иначе «компенсация морального вреда»
# попал бы в общее «компенсация».
CLAIM_BASIS_ANCHORS: list[tuple[re.Pattern[str], str]] = [
    (
        re.compile(
            r"расход\w*\s+на\s+(?:[\w-]+\s+){0,4}"
            r"(?:представител\w+|юрист\w+|адвокат\w+|юридическ\w*\s+услуг)",
            re.I,
        ),
        "расходы на представителя",
    ),
    (
        re.compile(r"процент\w*\s+за\s+пользовани\w+", re.I),
        "проценты за пользование денежными средствами",
    ),
    (
        re.compile(r"(?:компенсаци\w+\s+)?моральн\w*\s+вред", re.I),
        "компенсация морального вреда",
    ),
    (
        re.compile(
            r"неустойк\w*|пен[яи]|штраф\w*|"
            r"неосновательн\w+\s+обогащен\w*",
            re.I,
        ),
        "неустойка и санкции",
    ),
    (
        re.compile(r"компенсац\w*", re.I),
        "компенсация",
    ),
    (
        re.compile(r"убытк\w*|реальный\s+ущерб|ущерб", re.I),
        "убытки",
    ),
    (
        re.compile(r"задолженност\w*|долг|стоимость\s+товара", re.I),
        "задолженность по договору",
    ),
]

# Основания без денежной суммы.
NON_MONEY_BASES = frozenset(
    {
        "признание договора недействительным",
        "признание права",
        "обязать совершить действие",
        "расторжение договора",
        "отказ от исполнения договора",
    }
)


def claim_basis_match(text: str) -> tuple[str, re.Match[str]] | None:
    """Основание требования вместе с его местом в тексте.

    Место нужно, чтобы взять сумму, относящуюся именно к этому
    основанию. В окне с несколькими пунктами («взыскать долг 5000 руб.
    и неустойку 1000 руб.») первая сумма принадлежит соседнему
    пункту, и без привязки к основанию неустойка получала чужую
    сумму.
    """
    for pattern, basis in CLAIM_BASIS_PATTERNS:
        match = pattern.search(text)
        if match is not None:
            return basis, match
    return None


def claim_basis(text: str) -> str | None:
    """Основание требования по тексту фразы, либо None."""
    found = claim_basis_match(text)
    return found[0] if found is not None else None
